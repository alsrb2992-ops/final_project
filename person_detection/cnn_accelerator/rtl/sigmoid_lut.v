        if (!rst_n) begin
            out_valid <= 1'b0;
            // prob_out <= 8'd0; // BRAM 출력 레지스터와 충돌하는 비동기 리셋 제거
        end else begin
            out_valid <= in_valid;
            // 유효한 입력이 들어왔을 때, 계산된 lut_idx를 바탕으로 LUT 값을 출력합니다.
            if (in_valid) begin
                prob_out <= lut[lut_idx];
            end
        end
    end

