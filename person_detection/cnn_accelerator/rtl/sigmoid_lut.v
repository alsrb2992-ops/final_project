        if (!in_acc[39] && in_acc[39:15] != 0) begin
            // [양수 오버플로우] 값이 +7.9375를 초과하는 경우
            // 최대 양수 인덱스인 127로 포화시킵니다. (출력 확률 ≈ 255)
            lut_idx = 8'd127;
        end else if (in_acc[39] && in_acc[39:15] != {25{1'b1}}) begin
            // [음수 오버플로우] 값이 -8.0 미만으로 떨어지는 경우
            // 최소 음수 인덱스인 128로 포화시킵니다. (출력 확률 ≈ 0)
            // 주의: 인덱스 255는 -0.0625를 의미하므로, 매우 작은 값은 128로 가야 맞습니다.
            lut_idx = 8'd128;
        end else begin
            // [정상 범위] 16bit 이내의 값인 경우
            // in_acc[15:0] 중 상위 8비트(정수 4비트 + 소수 상위 4비트)를 인덱스로 취합니다.
            lut_idx = in_acc[15:8];
        end
    end

    // ── LUT 읽기 (동기식 순차 회로) ─────────────────────────────────────────────
